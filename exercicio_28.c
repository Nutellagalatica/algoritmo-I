/*O programa começa declarando uma variável do tipo float chamada n1. A variável float é usada para armazenar números reais, ou seja, números que podem ter casas decimais.

O valor 1.69 é atribuído à variável n1. Isso significa que o programa está guardando o número 1.69 dentro da variável n1.

O printf é usado para exibir o valor de n1 na tela. A expressão %f dentro da string indica que queremos imprimir um número do tipo float (número real com casas decimais).

O return 0; indica que o programa foi executado corretamente e chegou ao fim.
*/
#include <stdio.h>
int main(){
    float n1;
    n1 = 1.69;
    printf("valor de n1 %f \n", n1);
    return 0;
}
 